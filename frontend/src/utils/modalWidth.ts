// 弹窗 / 抽屉宽度的唯一出口。
//
// 为什么要有这个函数，而不是在模板里直接写 `'min(560px, 94vw)'`：
// 全站十二个弹窗与抽屉此前各写一遍这个字符串，于是出现了两种漂移 ——
//   · ChannelsView 的「测试连通性」写的是裸数字 440，没有任何窄屏保护，
//     窗口一窄（或浏览器缩放）弹窗比视口还宽，两侧被裁掉；
//   · DailyReport 的「昨日战报」写的是 92vw，与其余十一处的 94vw 不一致 ——
//     两个值肉眼分不出，但「全站同一条约定」这句话就不成立了。
// 值本身不难写，难的是**每次都记得写**，所以把它变成一个函数 +
// 一条契约断言（check-contracts.mjs 的「弹窗宽度契约」一节：
// 每个 a-modal / a-drawer 的 :width 都必须来自这里，且模板里不许再出现字面 vw）。
//
// 为什么是 94vw：给窄视口留出左右各 3vw 的呼吸，同时保证在 antd 的
// 居中定位下不会贴边。桌面端这个上限永远不生效（560px << 94vw），
// 它的作用只在窄窗口与高缩放下兜底。
export function modalWidth(px: number): string {
  return `min(${px}px, 94vw)`
}
